"""Run with python -m src.main; stdout belongs exclusively to MCP."""
import logging
import sys
from contextlib import asynccontextmanager
from fastmcp import FastMCP
from src.config import Config
from src.deps import Deps
from src.middleware import ErrorMiddleware
from src import resources
from src.tools import registry


def configure_logging():
    logging.basicConfig(level=logging.INFO, stream=sys.stderr, format="%(levelname)s %(name)s: %(message)s", force=True)


def build_server(config: Config | None = None, *, deps: Deps | None = None) -> FastMCP:
    deps = deps or Deps(config or Config.from_env())
    groups = registry.configure(deps)

    @asynccontextmanager
    async def lifespan(server):
        await deps.open()
        try:
            yield {"deps": deps}
        finally:
            await deps.close()

    instructions = ("Local owned workbench evidence. Registered tools: " + ", ".join(sorted(deps.selected)) +
        ". Unknown observations stay null. No public writes, windows, arbitrary commands or protected-player access. "
        "Annotations are hints, not authorization. A timeout never authorizes replay; inspect the existing attempt.")
    mcp = FastMCP("ls-workbench", version="0.1.0", lifespan=lifespan,
                  instructions=instructions, mask_error_details=True, strict_input_validation=True)
    mcp.add_middleware(ErrorMiddleware(deps))
    registry.register(mcp, deps, groups)
    resources.register(mcp, deps)
    return mcp


def main():
    configure_logging()
    try:
        server = build_server()
    except ValueError as exc:
        # Configuration errors are generated by this package, not backend messages.
        logging.getLogger("ls_workbench").error("Startup configuration rejected: %s", exc)
        raise SystemExit(2) from None
    server.run(transport="stdio", show_banner=False, log_level="WARNING")


if __name__ == "__main__":
    main()
